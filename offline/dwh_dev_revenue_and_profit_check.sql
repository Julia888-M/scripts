SELECT 
month(`Дата`) as `month`
--, `Артикул`
--, `Партнер планирования код`
, `Статья`
, `Сценарий`
, sum(`Value`) as `Value`
--, `Выручка план-цель, руб без НДС`
--, `Выручка план-цель, шт`
--, `Себестоимость план-цель, руб без НДС`
--, `Коммерческие расходы план-цель, руб без НДС`
--, `Выручка прогноз, руб без НДС`
--, `Выручка прогноз, шт`
--, `Себестоимость прогноз, руб без НДС`
--, `Коммерческие расходы прогноз, руб без НДС`
--, `Выручка факт, руб без НДС`
--, `Выручка факт, шт`
--, `Себестоимость факт, руб без НДС`
--, `Коммерческие расходы факт, руб без НДС`
--, `КП план-цель, руб без НДС`
--, `КП ежемесячно, руб без НДС`
, sum(`КП факт, руб без НДС`) as `КП факт, руб без НДС`
--, `Заказы, руб без НДС`
--, `Прочие КУ`
--, `Номер заказа`
--, `Количество заказов`
--, `Выручка на начало квартала, руб без НДС`
--, `КП на начало квартала, руб без НДС`
--, `Цена продажи, руб без НДС`
--, `Цена прайса, руб без НДС`
--, `Выручка по цене прайса, руб без НДС`
--, `Еженедельный прогноз, шт`
--, `Еженедельный прогноз, руб с НДС`
--, `Еженедельный прогноз, руб без НДС`
FROM finance.revenue_and_profit_prices
where `Статья`='КП, руб без НДС'
and `Сценарий`='Факт'
and `Партнер планирования код` not in ('ЕР-ЕР000387','ЕР-ЕР003862','ЕР-ЕР004646','ЦБ-ЦБ000357','УТ-00000002','ЕР-ЕР005789','ЕР-ЕР006741')
and `Дата`>='2026-01-01'
group by 
month(`Дата`)
, `Статья`
, `Сценарий`