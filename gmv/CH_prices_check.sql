SELECT 
toMonth(`Дата`) as "Месяц"
--, `Артикул`
--, `Партнер планирования код`
, `Статья`
, `Сценарий`
, sum(`Value`) as Value
, sum(`Цена продажи, руб без НДС`) as "Цена продажи, руб без НДС"
, sum(`Цена прайса, руб без НДС`) as "Цена прайса, руб без НДС"
, sum(`Выручка по цене прайса, руб без НДС`) as "Выручка по цене прайса, руб без НДС"
FROM finance.revenue_and_profit_prices
where `Дата`<='2025-12-31'
and `Сценарий`='Факт'
and `Статья`='Выручка по цене прайса, руб без НДС'
and `Партнер планирования код`='ЕР-ЕР001262'
group by 
toMonth(`Дата`)
--, `Артикул`
--, `Партнер планирования код`
, `Статья`
, `Сценарий`
order by "Месяц" ASC
;